/**
 * Generates the ABI module used by apps/api (packages/shared/src/abis.ts) directly from
 * the Hardhat build artifacts in artifacts/contracts/ — the output of the Solidity
 * compiler, not hand-written mirrors (packages/shared/README.md "Blockchain ABI artifacts";
 * formerly FLAG #1 in apps/api/src/blockchain.ts).
 *
 * Run after compiling the contracts — `npm run build` here does both — and commit the
 * regenerated module so consumers never need the Solidity toolchain.
 *
 * The generated module exports the ABIs as ethers human-readable signature strings (the
 * same representation `ethers.Contract` consumes), derived mechanically from the compiler
 * output so a contract change surfaces as a reviewable, importable diff.
 */
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

import { Interface } from "ethers";

const scriptDir = dirname(fileURLToPath(import.meta.url)); // contracts/scripts
const contractsDir = join(scriptDir, "..");
const sharedSrcDir = join(contractsDir, "..", "packages", "shared", "src");

/** Contract name → exported ABI constant name. Order fixes the module's output order. */
const CONTRACTS = [
  ["WorkflowFactory", "WORKFLOW_FACTORY_ABI"],
  ["Workflow", "WORKFLOW_ABI"],
];

async function readAbiSignatures(contractName) {
  const artifactPath = join(
    contractsDir,
    "artifacts",
    "contracts",
    `${contractName}.sol`,
    `${contractName}.json`,
  );

  let artifact;
  try {
    artifact = JSON.parse(await readFile(artifactPath, "utf8"));
  } catch (error) {
    if (error && error.code === "ENOENT") {
      throw new Error(
        `Missing Hardhat artifact for ${contractName} at ${artifactPath}.\n` +
          "Compile the contracts first: npm run build (in contracts/).",
      );
    }
    throw error;
  }

  // Human-readable signature strings straight from the compiler output. The constructor
  // is dropped: the API only talks to deployed instances, it never deploys these itself.
  const signatures = Interface.from(artifact.abi)
    .format()
    .filter((signature) => !signature.startsWith("constructor"));

  if (signatures.length === 0) {
    throw new Error(`Artifact for ${contractName} has no function or event fragments: ${artifactPath}`);
  }
  return signatures;
}

function renderModule(abis) {
  const lines = [
    "// ---------------------------------------------------------------------------",
    "// AUTO-GENERATED FILE — do not edit by hand.",
    "//",
    "// Generated by contracts/scripts/generate-abis.mjs from the Hardhat build artifacts",
    "// (contracts/artifacts/contracts/*.sol/*.json). After changing the Solidity sources,",
    "// regenerate and commit this file in the same commit:",
    "//",
    "//   cd contracts && npm run build   # or: npm run gen:abis",
    "//",
    "// ---------------------------------------------------------------------------",
    "",
  ];

  for (const [contractName, exportName] of CONTRACTS) {
    lines.push(`/** ABI of contracts/contracts/${contractName}.sol, as compiled by Hardhat. */`);
    lines.push(`export const ${exportName} = [`);
    for (const signature of abis[contractName]) {
      lines.push(`  ${JSON.stringify(signature)},`);
    }
    lines.push("] as const;");
    lines.push("");
  }

  return `${lines.join("\n")}\n`;
}

const abis = new Map();
for (const [contractName] of CONTRACTS) {
  abis.set(contractName, await readAbiSignatures(contractName));
}

const targetPath = join(sharedSrcDir, "abis.ts");
await writeFile(targetPath, renderModule(Object.fromEntries(abis)), "utf8");

const total = [...abis.values()].reduce((sum, signatures) => sum + signatures.length, 0);
console.log(`Generated ${relative(process.cwd(), targetPath)} (${total} ABI fragments)`);
